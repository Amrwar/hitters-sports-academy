"""Generates src/components/brand/logo-paths.ts and crops brand photos from the references."""
import os, shutil, sys
sys.path.insert(0, os.path.dirname(__file__))
from logo_geometry import wordmark, letter_H, skew, path_d, TAN
from PIL import Image

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
os.chdir(ROOT)

polys, total = wordmark()
shift = TAN * 100


def paths(polys):
    out = []
    for outer, hole in polys:
        s = path_d([(x + shift, y) for x, y in skew(outer)])
        if hole:
            s += " " + path_d([(x + shift, y) for x, y in skew(hole)])
        out.append(s)
    return out


wm = paths(polys)
hp, hw = letter_H()
mono = paths([(p, None) for p in hp])

lines = [
    "// Generated by scripts/build_brand_assets.py - do not hand edit.",
    "// Unskewed geometry (cap height 100) skewed by -28deg (tan 0.54), shifted so min x = 0.",
    f"export const WORDMARK_VIEWBOX = {{ width: {total + shift:.0f}, height: 100 }};",
    "export const WORDMARK_PATHS: string[] = [",
    *[f'  "{p}",' for p in wm],
    "];",
    f"export const MONOGRAM_VIEWBOX = {{ width: {hw + shift:.0f}, height: 100 }};",
    "export const MONOGRAM_PATHS: string[] = [",
    *[f'  "{p}",' for p in mono],
    "];",
    "",
]
os.makedirs("src/components/brand", exist_ok=True)
with open("src/components/brand/logo-paths.ts", "w") as f:
    f.write("\n".join(lines))
print("wordmark viewBox", total + shift, "monogram", hw + shift)

os.makedirs("public/brand/reference", exist_ok=True)
a = Image.open("padel1.jpeg")
# Logo-free crops of the reference photography (the wordmark band is excluded).
a.crop((0, 36, 982, 250)).save("public/brand/court-net.jpg", quality=88)       # net + racket head
a.crop((0, 365, 982, 588)).save("public/brand/court-line.jpg", quality=88)     # turf, white line, ball
a.crop((0, 596, 982, 815)).save("public/brand/court-rackets.jpg", quality=88)  # racket head, ball, glow ring
a.crop((0, 925, 982, 1140)).save("public/brand/court-handles.jpg", quality=88) # handles + balls
b = Image.open("padel2.jpeg")
b.crop((660, 10, 1255, 665)).save("public/brand/monogram-3d.jpg", quality=90)
shutil.copy("padel1.jpeg", "public/brand/reference/padel1.jpeg")
shutil.copy("padel2.jpeg", "public/brand/reference/padel2.jpeg")
print("assets ok")
